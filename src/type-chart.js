// 攻击属性 × 防御方全部属性（倍率相乘；倍率可为 0，表示该属性免疫，不能用 `|| 1` 兜底）
export function typeMult(atkType, defTypes) {
  let m = 1;
  const c = chart[atkType] || {};
  for (const t of defTypes) m *= c[t] ?? 1;
  return m;
}

export function describeMult(m) {
  if (m === 0) return '无效';
  if (m >= 2) return '效果绝佳';
  if (m < 1) return '收效甚微';
  return '效果普通';
}
